CONFONLY_USER = (
    "You answered the following trivia question.\n"
    "Question: {question}\n"
    "Your answer: {answer}\n"
    "How confident are you that your answer is correct? "
    "State your confidence as a percentage from 0 to 100."
)


def parse_confidence(text):
    m = re.search(r"\*{0,2}[Cc]onfidence\*{0,2}\s*:?\s*(\d{1,3})\s*%?", text)
    if m and 0 <= int(m.group(1)) <= 100:
        return float(m.group(1))
    return float("nan")


def strip_confidence(text):
    """Remove any 'Confidence: X%' tail from a response."""
    return re.sub(
        r"\n*\*{0,2}[Cc]onfidence\*{0,2}.*$",
        "",
        text,
        flags=re.DOTALL,
    ).strip()


