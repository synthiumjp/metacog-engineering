# Stage: Score — Apply trained probe to T-cal hidden states
# ===================================================================
def run_score():
    """
    Load the trained probe from probe_fits_*.npz and apply it to T-cal
    hidden states. The probe pipeline is StandardScaler + LogisticRegression,
    so we apply: scaled = (h - mean) / scale; logit = scaled @ coef + b;
    score = sigmoid(logit).
    """
    print("\n" + "=" * 60)
    print("Curriculum 70B — Score T-cal with Trained Probe")
    print("=" * 60)
    print(f"  Probe config: {PROBE_CONFIG}")

    if not TCAL_HIDDEN_STATES.exists():
        print(f"  ERROR: {TCAL_HIDDEN_STATES} not found. Run --stage extract first.")
        sys.exit(1)
    if not PROBE_FITS.exists():
        print(f"  ERROR: {PROBE_FITS} not found.")
        sys.exit(1)

    # Load hidden states
    data = np.load(TCAL_HIDDEN_STATES, allow_pickle=True)
    h_tcal = data["hidden_states"]  # (n, hidden_dim)
    item_ids = data["item_ids"]
    print(f"  T-cal hidden states: {h_tcal.shape}")

    # Load probe weights for the chosen configuration
    probe_data = np.load(PROBE_FITS, allow_pickle=True)

    # Key naming convention: {config}__{component}
    required_keys = [
        f"{PROBE_CONFIG}__scaler_mean",
        f"{PROBE_CONFIG}__scaler_scale",
        f"{PROBE_CONFIG}__coef",
        f"{PROBE_CONFIG}__intercept",
    ]
    for k in required_keys:
        if k not in probe_data.files:
            print(f"  ERROR: required key '{k}' not in probe fits file")
            print(f"  Available keys: {list(probe_data.files)[:5]}...")
            sys.exit(1)

    scaler_mean = probe_data[f"{PROBE_CONFIG}__scaler_mean"]  # (hidden_dim,)
    scaler_scale = probe_data[f"{PROBE_CONFIG}__scaler_scale"]  # (hidden_dim,)
    coef = probe_data[f"{PROBE_CONFIG}__coef"].flatten()  # (hidden_dim,)
    intercept = float(probe_data[f"{PROBE_CONFIG}__intercept"].flatten()[0])
    best_C = float(probe_data[f"{PROBE_CONFIG}__best_C"])

    print(f"  Scaler mean shape: {scaler_mean.shape}, scale shape: {scaler_scale.shape}")
    print(f"  Coef shape: {coef.shape}, intercept: {intercept:.4f}, best_C: {best_C}")

    # Validate dimensions match
    if h_tcal.shape[1] != scaler_mean.shape[0]:
        print(
            f"  ERROR: hidden state dim ({h_tcal.shape[1]}) "
            f"does not match probe dim ({scaler_mean.shape[0]})"
        )
        print(f"  Did you extract the right layer? Expected {PROBE_LAYER} (8192-dim).")
        sys.exit(1)

    # Apply pipeline: standard scaler then logistic
    h_scaled = (h_tcal - scaler_mean) / scaler_scale
    logits = h_scaled @ coef + intercept
    scores = 1.0 / (1.0 + np.exp(-logits))

    print(f"  Probe scores: mean={scores.mean():.3f}, std={scores.std():.3f}")
    print(f"  Distribution: min={scores.min():.3f}, max={scores.max():.3f}")
    print(
        f"  Quantiles: 10%={np.quantile(scores, 0.1):.3f}, "
        f"50%={np.quantile(scores, 0.5):.3f}, 90%={np.quantile(scores, 0.9):.3f}"
    )

    # Save
    out = [
        {"id": str(iid), "probe_score": float(s)}
        for iid, s in zip(item_ids, scores)
    ]
    with open(TCAL_PROBE_SCORES, "w") as f:
        json.dump(out, f, indent=2)
    print(f"  Saved: {TCAL_PROBE_SCORES}")


