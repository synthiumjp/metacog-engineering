# Stage: Prep — Create Stage 2 training data with probe-derived targets
# ===================================================================
def run_prep():
    """
    Create training data where each item's confidence target is the probe
    score (in 0-100 integer percentage). No binning, no balancing, no
    synthetic labels. This is the actual continuation of probe-targeted
    training.
    """
    print("\n" + "=" * 60)
    print("Curriculum 70B — Format Stage 2 Training Data")
    print("=" * 60)

    if not TCAL_PROBE_SCORES.exists():
        print(f"  ERROR: {TCAL_PROBE_SCORES} not found. Run --stage score first.")
        sys.exit(1)

    # Load probe scores
    with open(TCAL_PROBE_SCORES) as f:
        probe_scores_list = json.load(f)
    probe_score_map = {item["id"]: item["probe_score"] for item in probe_scores_list}
    print(f"  Probe scores: {len(probe_score_map)}")

    # Load T-cal responses for question + answer text
    with open(TCAL_RESPONSES) as f:
        tcal = json.load(f)

    # Build training items
    train_lines = []
    target_values = []
    missing = 0

    for item in tcal:
        iid = item.get("question_id", item.get("id", ""))
        question = item.get("question", "")
        raw_response = item.get("raw_response", "")
        answer = strip_confidence(item.get("parsed_answer", raw_response))

        if not question or not answer:
            continue

        # Look up probe score
        if iid not in probe_score_map:
            missing += 1
            continue
        score = probe_score_map[iid]

        # Map probe score [0, 1] to integer percentage [0, 100]
        # This is the same target derivation used at 7-32B
        target_pct = int(round(score * 100))
        target_pct = max(0, min(100, target_pct))

        user_content = CONFONLY_USER.format(question=question, answer=answer)
        train_lines.append(
            {
                "messages": [
                    {"role": "user", "content": user_content},
                    {"role": "assistant", "content": f"Confidence: {target_pct}%"},
                ]
            }
        )
        target_values.append(target_pct)

    if missing > 0:
        print(f"  Warning: {missing} items had no probe score (skipped)")

    target_arr = np.array(target_values)
    print(f"  Training items: {len(train_lines)}")
    print(f"  Target distribution:")
    print(f"    mean: {target_arr.mean():.1f}, std: {target_arr.std():.1f}")
    print(f"    min: {target_arr.min()}, max: {target_arr.max()}")
    print(f"    quantiles: 10%={np.quantile(target_arr, 0.1):.0f}, 50%={np.quantile(target_arr, 0.5):.0f}, 90%={np.quantile(target_arr, 0.9):.0f}")
    print(f"    pct above 90%: {(target_arr >= 90).mean():.1%}")
    print(f"    pct below 30%: {(target_arr <= 30).mean():.1%}")

    # Diagnostic: does the distribution have enough low-confidence signal?
    low_conf_count = (target_arr <= 30).sum()
    if low_conf_count < 50:
        print(f"  WARNING: only {low_conf_count} items have target ≤ 30%.")
        print(f"  This may produce a label-entropy collapse similar to Phase 0.")
        print(f"  Consider whether to balance or bin in this case.")

    # Save
    train_path = OUTPUT_DIR / "train.jsonl"
    valid_path = OUTPUT_DIR / "valid.jsonl"
    test_path = OUTPUT_DIR / "test.jsonl"

    # Shuffle deterministically before split
    rng = np.random.default_rng(42)
    indices = rng.permutation(len(train_lines))
    train_lines = [train_lines[i] for i in indices]

    n_train = int(0.95 * len(train_lines))
    train_split = train_lines[:n_train]
    valid_split = train_lines[n_train:]

    with open(train_path, "w") as f:
        for line in train_split:
            f.write(json.dumps(line) + "\n")
    with open(valid_path, "w") as f:
        for line in valid_split:
            f.write(json.dumps(line) + "\n")
    with open(test_path, "w") as f:
        for line in valid_split[:20]:
            f.write(json.dumps(line) + "\n")

    print(f"  Train: {len(train_split)} items")
    print(f"  Valid: {len(valid_split)} items")

    # LoRA config matching v1 adapter
    import yaml

    config = {
        "lora_parameters": {
            "rank": 16,
            "scale": 2.0,
            "dropout": 0.05,
        }
    }
    config_path = OUTPUT_DIR / "lora_config.yaml"
    with open(config_path, "w") as f:
        yaml.dump(config, f)

    print(f"  Saved: {train_path}")
    print(f"  Saved: {config_path}")


