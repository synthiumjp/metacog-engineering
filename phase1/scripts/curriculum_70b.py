"""
curriculum_70b.py — Curriculum training for Llama 70B

The curriculum hypothesis: standard PT-CSFT at 70B fails because the model
must simultaneously (a) leave the ceiling prior and (b) align confidence with
correctness. Balanced confonly v1 succeeded at (a) but did not solve (b).
This script tests whether resuming from v1 with probe-derived targets (the
actual continuation of PT-CSFT) can solve (b) now that the ceiling is broken.

Stage 1: balanced confonly v1 (already done; VRS Valid, conf_mean 63.8).
Stage 2: resume with probe-derived continuous targets on T-cal items.

Targets are derived from the trained linear probe applied to T-cal hidden
states. No correctness-label binning, no balancing, no synthetic jitter.

Probe config: middle_last_answer_token (T-eval AUROC = 0.834, the strongest
probe in the grid). This is the same target source used in the §11 middle-
layer ablation that produced the best PT-CSFT results at 7-32B scale. The
primary probe in the paper is last_last_answer_token (T-eval AUROC = 0.803);
we use middle here because it carries more training signal.

T-cal hidden states are loaded from the existing step1 npz file (no extraction
needed; the original step1_baseline_phase1.py already saved them).

    python3 scripts/curriculum_70b.py --stage validate  # Sanity check (~1 min)
    python3 scripts/curriculum_70b.py --stage load      # Load existing T-cal states (~5s)
    python3 scripts/curriculum_70b.py --stage score     # Apply probe → T-cal targets (~1m)
    python3 scripts/curriculum_70b.py --stage prep      # Format training data (~1m)
    python3 scripts/curriculum_70b.py --stage train     # Resume training from v1 (~1h)
    python3 scripts/curriculum_70b.py --stage eval      # Text + logit eval (~4h)
    python3 scripts/curriculum_70b.py --stage all       # ~5h end-to-end (skips validate)
"""

