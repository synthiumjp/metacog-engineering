PROBE_CONFIG = "middle_last_answer_token"
PROBE_LAYER = "middle"  # one of: first, middle, last
PROBE_TOKEN = "last_answer"  # one of: last_answer, pre_answer

# Stage 1 outputs (will be generated by this script)
TCAL_HIDDEN_STATES = OUTPUT_DIR / f"hidden_states_tcal_{PROBE_LAYER}.npz"
TCAL_PROBE_SCORES = OUTPUT_DIR / f"tcal_probe_scores_{PROBE_CONFIG}.json"

