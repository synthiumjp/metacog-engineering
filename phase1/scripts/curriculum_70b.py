MODEL_PATH = os.path.expanduser(
    "~/mnt/models-lan/foresight/synthesis-archive/Meta-Llama-3.1-70B-Instruct-bf16-CORRECTED"
)
MODEL_NAME = "Meta-Llama-3.1-70B-Instruct-bf16-CORRECTED"

V1_ADAPTER = f"results_raw/finetune/{MODEL_NAME}/balanced_confonly/adapters"
OUTPUT_DIR = Path("results_raw/domain_gen/curriculum_70b")

# Stage 1 inputs
TCAL_RESPONSES = Path(f"results_raw/step1/tcal_greedy_responses_{MODEL_NAME}.json")
PROBE_FITS = Path(f"results_raw/probe/probe_fits_{MODEL_NAME}.npz")
PROBE_METRICS = Path(f"results_raw/probe/probe_metrics_{MODEL_NAME}.json")

# Probe configuration to use as target source.
# Options: first_pre_answer_token, first_last_answer_token,
#          middle_pre_answer_token, middle_last_answer_token,
#          last_pre_answer_token, last_last_answer_token.
