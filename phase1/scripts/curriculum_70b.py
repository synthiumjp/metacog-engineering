# Stage: Load — Read existing T-cal hidden states (skip extraction)
# ===================================================================
def run_load():
    """
    Load pre-extracted T-cal hidden states from the existing step1 npz file.

    The original step1_baseline_phase1.py extracted hidden states for all
    items at three layers (first/middle/last) and two positions (pre_answer/
    last_answer_token) and saved them to:
        results_raw/step1/hidden_states_tcal_{model_name}.npz

    Keys are of the form: {question_id}__{layer}__{position}
    Each value is a (hidden_dim,) float32 array.

    This stage extracts the relevant configuration into a flat (n, dim) array
    keyed by question_id, ready for probe scoring.
    """
    print("=" * 60)
    print("Curriculum 70B — Load T-cal Hidden States")
    print("=" * 60)
    print(f"  Probe config: {PROBE_CONFIG}")
    print(f"  Layer: {PROBE_LAYER}, Token: {PROBE_TOKEN}")

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    if TCAL_HIDDEN_STATES.exists():
        print(f"  Hidden states already loaded: {TCAL_HIDDEN_STATES}")
        print(f"  Delete to regenerate, or skip to --stage score")
        return

    # Source: existing step1 npz
    SOURCE_NPZ = Path(f"results_raw/step1/hidden_states_tcal_{MODEL_NAME}.npz")
    if not SOURCE_NPZ.exists():
        print(f"  ERROR: source file not found: {SOURCE_NPZ}")
        sys.exit(1)

    print(f"  Loading from: {SOURCE_NPZ}")
    src = np.load(SOURCE_NPZ, allow_pickle=True)
    all_keys = list(src.keys())
    print(f"  Source keys: {len(all_keys)}")

    # Filter to keys matching our probe config
    # Key format: {qid}__{layer}__{position}
    suffix = f"__{PROBE_LAYER}__{PROBE_TOKEN}_token"
    matching_keys = [k for k in all_keys if k.endswith(suffix)]
    print(f"  Matching '{suffix}' keys: {len(matching_keys)}")

    if not matching_keys:
        print(f"  ERROR: no keys ending with '{suffix}' found.")
        print(f"  Sample available keys: {all_keys[:5]}")
        sys.exit(1)

    # Extract vectors and qids
    states = []
    item_ids = []
    for k in matching_keys:
        # qid = everything before the layer/position suffix
        qid = k[: -len(suffix)]
        states.append(src[k])
        item_ids.append(qid)

    states_arr = np.array(states)
    item_ids_arr = np.array(item_ids)
    print(f"  Stacked shape: {states_arr.shape}")
    print(f"  Sample qids: {item_ids_arr[:3].tolist()}")

    np.savez(TCAL_HIDDEN_STATES, hidden_states=states_arr, item_ids=item_ids_arr)
    print(f"  Saved: {TCAL_HIDDEN_STATES}")


