# Stage: Train — Resume from v1 adapter with probe-derived targets
# ===================================================================
def run_train():
    print("\n" + "=" * 60)
    print("Curriculum 70B — Stage 2 Training (resume from v1)")
    print("=" * 60)

    adapter_dir = OUTPUT_DIR / "adapters"
    os.makedirs(adapter_dir, exist_ok=True)

    cmd = [
        "python3",
        "-m",
        "mlx_lm.lora",
        "--model",
        MODEL_PATH,
        "--data",
        str(OUTPUT_DIR),
        "--train",
        "--iters",
        str(STAGE2_ITERS),
        "--batch-size",
        "2",
        "--learning-rate",
        LR,
        "--adapter-path",
        str(adapter_dir),
        "--resume-adapter-file",
        V1_ADAPTER + "/adapters.safetensors",
        "--seed",
        "42",
        "-c",
        str(OUTPUT_DIR / "lora_config.yaml"),
    ]
    # NOTE: --grad-accumulation-steps removed; if needed, add via YAML config

    print(f"  Resuming from: {V1_ADAPTER}")
    print(f"  Stage 2 iters: {STAGE2_ITERS}")
    print(f"  Command: {' '.join(cmd)}")
    t0 = time.time()

    result = subprocess.run(cmd, capture_output=False)

    elapsed = time.time() - t0
    print(f"  Training completed in {elapsed:.0f}s")
    if result.returncode != 0:
        print(f"  ERROR: return code {result.returncode}")
        sys.exit(1)


