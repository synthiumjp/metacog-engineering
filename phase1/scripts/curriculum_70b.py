# Stage: Validate — 5-minute sanity check before committing 2h to extraction
# ===================================================================
def run_validate():
    """
    Sanity check before running the full curriculum pipeline.

    Loads pre-extracted T-cal hidden states from the existing step1 npz file,
    applies the probe to a 50-item subset, computes AUROC2 against the
    correctness labels in tcal_greedy_responses. Should approach the probe's
    T-eval AUROC (~0.83 for middle_last_answer_token), modulo sample noise.

    Cost: < 1 minute.
    """
    print("=" * 60)
    print("Curriculum 70B — Validate Pipeline")
    print("=" * 60)
    print(f"  Probe config: {PROBE_CONFIG}")
    print(f"  Layer: {PROBE_LAYER}, Position: {PROBE_TOKEN}")

    # Load source hidden states
    SOURCE_NPZ = Path(f"results_raw/step1/hidden_states_tcal_{MODEL_NAME}.npz")
    if not SOURCE_NPZ.exists():
        print(f"  ERROR: source file not found: {SOURCE_NPZ}")
        sys.exit(1)
    src = np.load(SOURCE_NPZ, allow_pickle=True)

    # Load T-cal correctness labels
    with open(TCAL_RESPONSES) as f:
        tcal = json.load(f)
    correctness_map = {item["question_id"]: bool(item.get("correct", False)) for item in tcal}

    # Load probe weights
    probe_data = np.load(PROBE_FITS, allow_pickle=True)
    scaler_mean = probe_data[f"{PROBE_CONFIG}__scaler_mean"]
    scaler_scale = probe_data[f"{PROBE_CONFIG}__scaler_scale"]
    coef = probe_data[f"{PROBE_CONFIG}__coef"].flatten()
    intercept = float(probe_data[f"{PROBE_CONFIG}__intercept"].flatten()[0])

    # Apply probe to a subset
    suffix = f"__{PROBE_LAYER}__{PROBE_TOKEN}_token"
    sample_keys = [k for k in src.keys() if k.endswith(suffix)][:50]
    print(f"  Validation sample: {len(sample_keys)} items")

    scores = []
    correct = []
    for k in sample_keys:
        qid = k[: -len(suffix)]
        if qid not in correctness_map:
            continue
        h = src[k]
        h_scaled = (h - scaler_mean) / scaler_scale
        logit = h_scaled @ coef + intercept
        score = 1.0 / (1.0 + np.exp(-logit))
        scores.append(float(score))
        correct.append(int(correctness_map[qid]))

    scores = np.array(scores)
    correct = np.array(correct)

    print(f"\n  N valid: {len(scores)}")
    print(f"  Score range: [{scores.min():.3f}, {scores.max():.3f}]")
    if (correct == 1).any():
        print(f"  Mean score (correct): {scores[correct == 1].mean():.3f}")
    if (correct == 0).any():
        print(f"  Mean score (incorrect): {scores[correct == 0].mean():.3f}")

    if 0 < correct.sum() < len(correct):
        from sklearn.metrics import roc_auc_score
        auroc = roc_auc_score(correct, scores)
        print(f"  Sample AUROC2: {auroc:.3f}")
        print(f"  Expected (T-eval AUROC): 0.834")
        if auroc > 0.70:
            print(f"  ✓ Pipeline is correct. Safe to run --stage load.")
        elif auroc > 0.55:
            print(f"  ~ Pipeline produces weak signal. Probably sample-size effect; check with more items.")
        else:
            print(f"  ✗ Pipeline produces near-chance scores. Likely a probe-key or scaling mismatch.")
    else:
        print(f"  Cannot compute AUROC (insufficient class balance).")


