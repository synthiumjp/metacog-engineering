# Stage: Eval — Text + logit readout on T-eval
# ===================================================================
def run_eval():
    print("\n" + "=" * 60)
    print("Curriculum 70B — Evaluation")
    print("=" * 60)

    adapter_dir = OUTPUT_DIR / "adapters"

    with open(EVAL_RESPONSES_PATH) as f:
        eval_items = json.load(f)
    print(f"  Eval items: {len(eval_items)}")

    print(f"  Loading 70B + curriculum adapter...")
    import mlx.core as mx
    from mlx_lm import load, generate

    model, tokenizer = load(MODEL_PATH, adapter_path=str(adapter_dir))

    # Build digit token map for logit readout
    digit_ids = {}
    for d in range(101):
        toks = tokenizer.encode(str(d), add_special_tokens=False)
        if len(toks) == 1:
            digit_ids[d] = toks[0]
    max_digit = max(digit_ids.keys())
    digits = np.array(sorted(digit_ids.keys()))
    print(f"  Single-token digits: {len(digit_ids)}/101")

    results = []
    t0 = time.time()

    for i, item in enumerate(eval_items):
        question = item["question"]
        # Use the baseline answer (preserved in v1 eval), not the adapter's answer
        answer = strip_confidence(item.get("answer_text", item.get("raw_answer", "")))
        correct = item["correct"]

        user_msg = CONFONLY_USER.format(question=question, answer=answer)
        prompt = tokenizer.apply_chat_template(
            [{"role": "user", "content": user_msg}],
            tokenize=False,
            add_generation_prompt=True,
        )

        response = generate(model, tokenizer, prompt=prompt, max_tokens=32, verbose=False)
        text_conf = parse_confidence(response)

        # Logit readout: read softmax distribution over digit tokens after "Confidence: "
        prompt_prefix = prompt + "Confidence: "
        tokens = tokenizer.encode(prompt_prefix)

        logit_ev = float("nan")
        try:
            x = mx.array([tokens])
            logits = model(x)
            last_logits = logits[0, -1, :]
            d_logits = mx.array([last_logits[digit_ids[d]] for d in digits])
            d_probs = mx.softmax(d_logits)
            d_probs_np = np.array(d_probs.astype(mx.float32))
            logit_ev = float(np.sum((digits / max_digit) * d_probs_np)) * 100
            mx.eval(logits)
            del x, logits
        except Exception as e:
            if i < 3:
                print(f"  Error: {e}")

        results.append(
            {
                "id": item.get("id", f"q_{i}"),
                "correct": correct,
                "text_confidence": text_conf,
                "logit_confidence": logit_ev,
                "response": response[:100],
            }
        )

        if (i + 1) % 25 == 0:
            elapsed = time.time() - t0
            valid_l = [r for r in results if not np.isnan(r["logit_confidence"])]
            valid_t = [r for r in results if not np.isnan(r["text_confidence"])]
            if valid_l:
                from sklearn.metrics import roc_auc_score

                c = np.array([int(r["correct"]) for r in valid_l])
                lc = np.array([r["logit_confidence"] for r in valid_l])
                if c.sum() > 0 and c.sum() < len(c):
                    l_auc = roc_auc_score(c, lc)
                    t_auc = (
                        roc_auc_score(
                            np.array([int(r["correct"]) for r in valid_t]),
                            np.array([r["text_confidence"] for r in valid_t]),
                        )
                        if len(valid_t) > 10
                        else 0
                    )
                    print(
                        f"  [{i+1}/{len(eval_items)}]  text={t_auc:.3f} logit={l_auc:.3f}  elapsed={elapsed:.0f}s"
                    )

    # Final analysis
    from sklearn.metrics import roc_auc_score

    valid_l = [r for r in results if not np.isnan(r["logit_confidence"])]
    valid_t = [r for r in results if not np.isnan(r["text_confidence"])]
    c_l = np.array([int(r["correct"]) for r in valid_l])
    lc = np.array([r["logit_confidence"] for r in valid_l])
    c_t = np.array([int(r["correct"]) for r in valid_t])
    tc = np.array([r["text_confidence"] for r in valid_t])

    l_auc = roc_auc_score(c_l, lc) if c_l.sum() > 0 and c_l.sum() < len(c_l) else None
    t_auc = roc_auc_score(c_t, tc) if c_t.sum() > 0 and c_t.sum() < len(c_t) else None

    print(f"\n  {'='*60}")
    print(f"  Curriculum 70B Results")
    print(f"  {'='*60}")
    print(f"  Accuracy: {np.mean([r['correct'] for r in results]):.3f}")
    if l_auc is not None:
        print(f"  Logit AUROC₂: {l_auc:.3f}")
        print(f"  Logit conf mean: {lc.mean():.1f} (std {lc.std():.1f})")
    if t_auc is not None:
        print(f"  Text AUROC₂:  {t_auc:.3f}")
        print(f"  Text conf mean: {tc.mean():.1f} (std {tc.std():.1f})")
        print(f"  Ceiling (>=95%): {(tc >= 95).mean():.1%}")

    print(f"\n  Comparison:")
    print(f"    Baseline:                0.724")
    print(f"    Balanced confonly text:  0.682")
    print(f"    Balanced confonly logit: 0.746")
    print(f"    Gentlest logit (failed): 0.679")
    if l_auc is not None:
        print(f"    Curriculum logit:        {l_auc:.3f}")
    if t_auc is not None:
        print(f"    Curriculum text:         {t_auc:.3f}")

    if l_auc is not None and l_auc > 0.78:
        print(f"\n  ✓ Curriculum substantially exceeds baseline (>0.78)")
    elif l_auc is not None and l_auc > 0.746:
        print(f"\n  ~ Curriculum exceeds balanced confonly logit, modest")
    else:
        print(f"\n  ✗ Curriculum did not exceed balanced confonly logit (0.746)")

    save = {
        "method": "curriculum_70b_probe_targets",
        "stage1": "balanced_confonly_v1 (58 iters)",
        "stage2_iters": STAGE2_ITERS,
        "stage2_lr": LR,
        "stage2_targets": "probe-derived continuous (no balancing, no synthetic labels)",
        "n": len(results),
        "accuracy": float(np.mean([r["correct"] for r in results])),
        "logit_auroc2": float(l_auc) if l_auc is not None else None,
        "text_auroc2": float(t_auc) if t_auc is not None else None,
        "logit_conf_mean": float(lc.mean()) if l_auc is not None else None,
        "logit_conf_std": float(lc.std()) if l_auc is not None else None,
        "text_conf_mean": float(tc.mean()) if t_auc is not None else None,
        "text_conf_std": float(tc.std()) if t_auc is not None else None,
        "text_ceiling_rate": float((tc >= 95).mean()) if t_auc is not None else None,
    }
    with open(OUTPUT_DIR / "curriculum_results.json", "w") as f:
        json.dump(save, f, indent=2)
    with open(OUTPUT_DIR / "curriculum_responses.json", "w") as f:
        json.dump(results, f, indent=2)
    print(f"\n  Saved: {OUTPUT_DIR / 'curriculum_results.json'}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--stage",
        default="all",
        choices=["validate", "load", "score", "prep", "train", "eval", "all"],
    )
    args = parser.parse_args()

    if args.stage == "validate":
        run_validate()
        return
    if args.stage in ("load", "all"):
        run_load()
    if args.stage in ("score", "all"):
        run_score()
    if args.stage in ("prep", "all"):
        run_prep()
    if args.stage in ("train", "all"):
        run_train()
    if args.stage in ("eval", "all"):
        run_eval()


if __name__ == "__main__":
    main()
